#!/usr/bin/env bash
# Install gnome-terminal-restore for the current user. No root required, and
# nothing is written outside the paths reported at the end.
set -euo pipefail

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP="gnome-terminal-restore"

PREFIX="${PREFIX:-$HOME/.local}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
INTERVAL="30min"
WITH_AUTOSTART=1
WITH_HOOK=1
WITH_SYSTEMD=1
BASHRC="${BASHRC:-$HOME/.bashrc}"

usage() {
    cat <<'USAGE'
Usage: ./install.sh [options]

  --prefix DIR      install under DIR (default: $HOME/.local, or $PREFIX)
  --interval SPEC   snapshot interval: 15min, 30min, 1h, or any systemd
                    OnCalendar expression (default: 30min)
  --no-autostart    do not restore the layout automatically at login
  --no-hook         do not add the shell hook to ~/.bashrc
                    (directories are still saved; virtualenvs are not)
  --no-systemd      install the commands only, no timer or shutdown unit
  -h, --help        show this message

Environment: PREFIX, BASHRC, XDG_CONFIG_HOME are honoured.
USAGE
}

while [ $# -gt 0 ]; do
    case "$1" in
        --prefix) PREFIX="$2"; shift 2 ;;
        --prefix=*) PREFIX="${1#*=}"; shift ;;
        --interval) INTERVAL="$2"; shift 2 ;;
        --interval=*) INTERVAL="${1#*=}"; shift ;;
        --no-autostart) WITH_AUTOSTART=0; shift ;;
        --no-hook) WITH_HOOK=0; shift ;;
        --no-systemd) WITH_SYSTEMD=0; shift ;;
        -h|--help) usage; exit 0 ;;
        *) echo "install.sh: unknown option: $1" >&2; usage >&2; exit 2 ;;
    esac
done

BINDIR="$PREFIX/bin"
LIBDIR="$PREFIX/lib/$APP"
UNITDIR="$CONFIG_HOME/systemd/user"
AUTOSTARTDIR="$CONFIG_HOME/autostart"

# --- interval -> systemd OnCalendar ------------------------------------------
to_oncalendar() {
    case "$1" in
        *min)
            local n="${1%min}"
            [ "$n" -ge 1 ] && [ "$n" -le 59 ] || { echo "$1"; return; }
            echo "*:0/$n" ;;
        *h)
            local n="${1%h}"
            [ "$n" -ge 1 ] && [ "$n" -le 23 ] || { echo "$1"; return; }
            echo "0/$n:00" ;;
        *) echo "$1" ;;
    esac
}
ONCALENDAR="$(to_oncalendar "$INTERVAL")"

# --- dependency checks --------------------------------------------------------
missing=0
need() {
    command -v "$1" >/dev/null 2>&1 || { echo "missing required command: $1" >&2; missing=1; }
}
need python3
command -v gnome-terminal >/dev/null 2>&1 || \
    echo "warning: gnome-terminal not found on PATH; install it before using this tool" >&2
python3 - <<'PY' || echo "warning: python3-gi with Atspi is unavailable; window grouping will be
         disabled and every tab restored into one window. On Debian/Ubuntu:
         sudo apt install python3-gi gir1.2-atspi-2.0" >&2
import gi
gi.require_version("Atspi", "2.0")
from gi.repository import Atspi  # noqa: F401
PY
[ "$missing" -eq 0 ] || exit 1

# --- install the code ---------------------------------------------------------
mkdir -p "$BINDIR" "$LIBDIR"
rm -rf "$LIBDIR/gnome_terminal_restore"
cp -r "$SRC_DIR/src/gnome_terminal_restore" "$LIBDIR/"
cp "$SRC_DIR/shell/hook.bash" "$LIBDIR/hook.bash"

launcher() {  # $1 = command name, $2 = module
    cat > "$BINDIR/$1" <<LAUNCHER
#!/usr/bin/env python3
# Generated by ${APP}'s install.sh
import sys
sys.path.insert(0, "$LIBDIR")
from $2 import main
sys.exit(main())
LAUNCHER
    chmod 755 "$BINDIR/$1"
}
launcher gt-save gnome_terminal_restore.save
launcher gt-restore gnome_terminal_restore.restore

# --- shell hook ---------------------------------------------------------------
BEGIN_MARK="# >>> $APP >>>"
END_MARK="# <<< $APP <<<"
if [ "$WITH_HOOK" -eq 1 ]; then
    if [ -f "$BASHRC" ] && grep -qF "$BEGIN_MARK" "$BASHRC"; then
        echo "shell hook already present in $BASHRC"
    else
        {
            echo ""
            echo "$BEGIN_MARK"
            echo "[ -f \"$LIBDIR/hook.bash\" ] && . \"$LIBDIR/hook.bash\""
            echo "$END_MARK"
        } >> "$BASHRC"
        echo "shell hook added to $BASHRC"
    fi
fi

# --- systemd units ------------------------------------------------------------
render() { sed -e "s|@BINDIR@|$BINDIR|g" -e "s|@ONCALENDAR@|$ONCALENDAR|g" "$1" > "$2"; }

if [ "$WITH_SYSTEMD" -eq 1 ]; then
    mkdir -p "$UNITDIR"
    render "$SRC_DIR/systemd/gt-save.service.in"          "$UNITDIR/gt-save.service"
    render "$SRC_DIR/systemd/gt-save.timer.in"            "$UNITDIR/gt-save.timer"
    render "$SRC_DIR/systemd/gt-save-shutdown.service.in" "$UNITDIR/gt-save-shutdown.service"
    if command -v systemctl >/dev/null 2>&1; then
        systemctl --user daemon-reload
        systemctl --user enable --now gt-save.timer gt-save-shutdown.service
    else
        echo "warning: systemctl not found; units installed but not enabled" >&2
    fi
fi

# --- autostart ----------------------------------------------------------------
if [ "$WITH_AUTOSTART" -eq 1 ]; then
    mkdir -p "$AUTOSTARTDIR"
    render "$SRC_DIR/autostart/gt-restore.desktop.in" "$AUTOSTARTDIR/gt-restore.desktop"
    chmod 644 "$AUTOSTARTDIR/gt-restore.desktop"
fi

# --- report -------------------------------------------------------------------
cat <<SUMMARY

$APP installed.

  commands     $BINDIR/gt-save, $BINDIR/gt-restore
  library      $LIBDIR
  snapshots    ${XDG_DATA_HOME:-$HOME/.local/share}/$APP/snapshot.json
SUMMARY
if [ "$WITH_SYSTEMD" -eq 1 ]; then
    echo "  timer        $UNITDIR/gt-save.timer (OnCalendar=$ONCALENDAR)"
    echo "  shutdown     $UNITDIR/gt-save-shutdown.service"
fi
if [ "$WITH_AUTOSTART" -eq 1 ]; then
    echo "  autostart    $AUTOSTARTDIR/gt-restore.desktop"
fi
if [ "$WITH_HOOK" -eq 1 ]; then
    echo "  shell hook   $BASHRC -> $LIBDIR/hook.bash"
fi

case ":$PATH:" in
    *":$BINDIR:"*) ;;
    *) echo ""; echo "note: $BINDIR is not on your PATH; add it to use gt-save/gt-restore by name" ;;
esac

cat <<'NEXT'

Next steps:
  1. Run  source ~/.bashrc  in any tab that is already open, so it starts
     reporting its virtualenv (new tabs do this automatically).
  2. Run  gt-save  to take a first snapshot, then  gt-restore --list  to see it.
NEXT
