"""Reopen the windows and tabs recorded in a snapshot."""
import argparse
import json
import os
import shlex
import subprocess
import sys
import time

from . import __version__
from . import paths, procs

TERMINAL = os.environ.get("GTR_TERMINAL", "gnome-terminal")
WINDOW_DELAY = 0.6


def load_snapshot(path):
    with open(path) as handle:
        return json.load(handle)


def user_shell():
    return os.path.basename(os.environ.get("SHELL", "")) or "bash"


def needs_rc(tab):
    """True when the tab carries state a plain shell would not reproduce."""
    return bool(tab.get("venv") or tab.get("conda_env") or not procs.is_shell(tab.get("cmd")))


def render_rc(tab):
    """A bash rc file that restores the user's normal shell, then the tab's environment."""
    lines = [
        "# Generated by gt-restore. Safe to delete; regenerated on every restore.",
        '[ -f "$HOME/.bashrc" ] && . "$HOME/.bashrc"',
    ]
    venv = tab.get("venv")
    if venv:
        activate = os.path.join(venv, "bin", "activate")
        quoted = shlex.quote(activate)
        lines.append(
            "if [ -f %s ]; then . %s; else echo 'gt-restore: virtualenv no longer exists: %s'; fi"
            % (quoted, quoted, venv)
        )
    conda_env = tab.get("conda_env")
    if conda_env and conda_env != "base":
        lines.append(
            "command -v conda >/dev/null 2>&1 && conda activate %s" % shlex.quote(conda_env)
        )
    command = (tab.get("cmd") or "").strip()
    if command and not procs.is_shell(command):
        # Deliberately not re-run: restoring a layout should never execute commands
        # on its own. It is put in the history so Up recalls it.
        lines.append("history -s %s" % shlex.quote(command))
        lines.append(
            "printf 'gt-restore: this tab was running: %%s\\n' %s" % shlex.quote(command)
        )
    return "\n".join(lines) + "\n"


def write_rc(tab, window_index, tab_index):
    directory = paths.rc_dir()
    os.makedirs(directory, exist_ok=True)
    path = os.path.join(directory, "w%d-t%d" % (window_index, tab_index))
    with open(path, "w") as handle:
        handle.write(render_rc(tab))
    return path


def build_command(window_index, tabs, use_rc=True):
    """The full terminal command line for one window and all of its tabs."""
    argv = [TERMINAL]
    for tab_index, tab in enumerate(tabs):
        cwd = tab["cwd"] if os.path.isdir(tab["cwd"]) else os.path.expanduser("~")
        argv += [
            "--window" if tab_index == 0 else "--tab",
            "--working-directory=" + cwd,
        ]
        if use_rc and needs_rc(tab):
            rc = write_rc(tab, window_index, tab_index)
            # -e is deprecated but is the only way to give each tab its own command
            argv += ["-e", "bash --rcfile %s" % shlex.quote(rc)]
    return argv


def describe(tab):
    parts = [tab["cwd"]]
    if tab.get("venv"):
        parts.append("venv:" + os.path.basename(tab["venv"].rstrip("/")))
    if tab.get("conda_env"):
        parts.append("conda:" + tab["conda_env"])
    if tab.get("cmd"):
        parts.append("was:" + tab["cmd"][:60])
    return "  |  ".join(parts)


def print_layout(windows, stream=sys.stdout):
    for index, tabs in enumerate(windows):
        print(
            "window %d (%d tab%s):" % (index, len(tabs), "" if len(tabs) == 1 else "s"),
            file=stream,
        )
        for tab in tabs:
            print("    " + describe(tab), file=stream)


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="gt-restore", description="Reopen the GNOME Terminal layout saved by gt-save."
    )
    parser.add_argument("--prev", action="store_true", help="use the previous snapshot")
    parser.add_argument("-l", "--list", action="store_true", help="print the layout and exit")
    parser.add_argument(
        "-n", "--dry-run", action="store_true", help="print the commands without running them"
    )
    parser.add_argument(
        "-w",
        "--window",
        type=int,
        action="append",
        metavar="N",
        help="restore only window N (repeatable)",
    )
    parser.add_argument(
        "--if-none",
        action="store_true",
        help="do nothing if a terminal is already open (used by the autostart entry)",
    )
    parser.add_argument(
        "-f", "--file", metavar="PATH", help="restore from a specific snapshot file"
    )
    parser.add_argument("--version", action="version", version="%(prog)s " + __version__)
    args = parser.parse_args(argv)

    if args.if_none and procs.terminal_running():
        print("gt-restore: a terminal is already open, nothing to do")
        return 0

    path = args.file or (paths.previous_snapshot_path() if args.prev else paths.snapshot_path())
    try:
        snapshot = load_snapshot(path)
    except OSError:
        print("gt-restore: no snapshot at %s" % path, file=sys.stderr)
        return 1
    except ValueError as exc:
        print("gt-restore: snapshot at %s is unreadable (%s)" % (path, exc), file=sys.stderr)
        return 1

    windows = snapshot.get("windows") or []
    if not windows:
        print("gt-restore: snapshot is empty", file=sys.stderr)
        return 1
    if not snapshot.get("grouped"):
        print(
            "gt-restore: this snapshot has no window grouping; restoring as one window",
            file=sys.stderr,
        )

    print_layout(windows)
    if args.list:
        return 0

    shell = user_shell()
    use_rc = shell == "bash"
    if not use_rc and any(needs_rc(tab) for tabs in windows for tab in tabs):
        print(
            "gt-restore: environment reactivation currently requires bash; your shell is %s, "
            "so directories are restored but virtualenvs are not" % shell,
            file=sys.stderr,
        )

    launched = 0
    for index, tabs in enumerate(windows):
        if args.window and index not in args.window:
            continue
        command = build_command(index, tabs, use_rc=use_rc)
        if args.dry_run:
            print("would run:", " ".join(shlex.quote(part) for part in command))
            continue
        try:
            subprocess.Popen(command, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        except OSError as exc:
            print("gt-restore: could not launch %s (%s)" % (TERMINAL, exc), file=sys.stderr)
            return 1
        launched += 1
        time.sleep(WINDOW_DELAY)  # let each window register before opening the next

    if not args.dry_run:
        print("\nrestored %d window(s)" % launched)
    return 0


if __name__ == "__main__":
    sys.exit(main())
